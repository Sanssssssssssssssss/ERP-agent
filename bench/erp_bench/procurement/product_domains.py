#!/usr/bin/env python3
"""Product domain definitions for procurement benchmark scenarios.

Each domain defines a product category with 10 finished-product variants
and 30 component templates used for BOM and vendor generation.
"""

from __future__ import annotations

from numpy.random import Generator
from pydantic import BaseModel, ConfigDict

from .solver import ProductSpec


class FinishedProductTemplate(BaseModel):
    name: str
    code: str
    list_price: float
    standard_price: float


class ComponentTemplate(BaseModel):
    name: str
    code: str
    list_price: float
    standard_price: float
    per_unit: int = 1
    per_unit_range: tuple[int, int] | None = None
    stock_range: tuple[int, int] | None = None

    def build_product(self, rng: Generator) -> ProductSpec:
        list_price = round(self.list_price * rng.uniform(0.95, 1.05), 2)
        standard_price = round(self.standard_price * rng.uniform(0.92, 1.08), 2)
        return ProductSpec(
            name=self.name,
            code=self.code,
            list_price_dollars=list_price,
            standard_price_dollars=standard_price,
            routes=("buy",),
        )

    def sample_per_unit(self, rng: Generator) -> int:
        if self.per_unit_range is None:
            return self.per_unit
        low, high = self.per_unit_range
        return low if low >= high else int(rng.integers(low, high + 1))


class ProductDomain(BaseModel):
    """A product category with multiple finished-product variants and shared components."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    label: str
    product_templates: tuple[FinishedProductTemplate, ...]
    component_templates: tuple[ComponentTemplate, ...]
    company_context: str
    product_category: str = "Industrial Equipment"
    adjacent_product_nouns: tuple[str, ...] = ()

    def build_product(self, rng: Generator) -> ProductSpec:
        template = self.product_templates[int(rng.integers(len(self.product_templates)))]
        list_price = round(template.list_price * rng.uniform(0.95, 1.05), 2)
        standard_price = round(template.standard_price * rng.uniform(0.92, 1.08), 2)
        return ProductSpec(
            name=template.name,
            code=template.code,
            category=self.product_category,
            list_price_dollars=list_price,
            standard_price_dollars=standard_price,
            routes=("buy",),
        )


