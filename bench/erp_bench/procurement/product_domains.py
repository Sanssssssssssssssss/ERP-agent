def _derive_adjacent_nouns(domain: ProductDomain, limit: int = 24) -> tuple[str, ...]:
    phrases: list[str] = []
    for template in (*domain.component_templates, *domain.product_templates):
        tokens = [token for token in template.name.replace("-", " ").split() if token]
        if len(tokens) >= 3:
            phrases.append(" ".join(tokens[-3:]))
        if len(tokens) >= 2:
            phrases.append(" ".join(tokens[-2:]))
    phrases.append(domain.label)
    seen: set[str] = set()
    unique: list[str] = []
    for phrase in phrases:
        cleaned = " ".join(phrase.split())
        if not cleaned or cleaned in seen:
            continue
        seen.add(cleaned)
        unique.append(cleaned)
        if len(unique) >= limit:
            break
    return tuple(unique)


